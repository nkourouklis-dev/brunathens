// Λογότυπο επιχείρησης: η εικόνα που ανέβασε ο ιδιοκτήτης, αλλιώς το εικονίδιο που διάλεξε μέσα σε κύκλο.
export function contrastText(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex || '')
  if (!m) return '#ffffff'
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16))
  return (r * 299 + g * 587 + b * 114) / 1000 > 150 ? '#111827' : '#ffffff'
}

export function BusinessMark({ business, size = 56, className = '' }) {
  const style = { width: size, height: size }
  if (business.hasLogo) {
    return (
      <span className={`mark mark-image ${className}`} style={style}>
        <img src={`/api/b/${business.slug}/logo?v=${business.logoVersion}`} alt={business.name} />
      </span>
    )
  }
  return (
    <span className={`mark ${className}`} style={{ ...style, background: business.textColor || contrastText(business.color), color: business.color }}>
      <Icon name={business.icon} size={Math.round(size * 0.52)} />
    </span>
  )
}

